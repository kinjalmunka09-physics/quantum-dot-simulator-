import matplotlib.pyplot as plt
import numpy as np
from scipy.interpolate import make_interp_spline

# Quantum dot widths (nm)
widths = np.array([2.0, 3.5, 5.0, 6.5, 8.0, 9.5])
smooth_x = np.linspace(2.0, 9.5, 500)

# Batch A: Reference simulated dataset
energy_a = np.array([3.38, 1.10, 0.54, 0.32, 0.21, 0.15])

# Batch B: Shifted simulated dataset
energy_b = np.array([3.10, 1.35, 0.72, 0.48, 0.35, 0.28])

spline_a = make_interp_spline(widths, energy_a, k=3)
spline_b = make_interp_spline(widths, energy_b, k=3)

smooth_y_a = spline_a(smooth_x)
smooth_y_b = spline_b(smooth_x)

plt.figure(figsize=(11, 6))

# Batch A
plt.plot(
    smooth_x, smooth_y_a,
    color="blue",
    linewidth=2.5,
    label="Batch A - Reference"
)

plt.scatter(
    widths, energy_a,
    color="blue",
    marker="o",
    s=65,
    zorder=5
)

# Batch B
plt.plot(
    smooth_x, smooth_y_b,
    color="red",
    linewidth=2.5,
    linestyle="--",
    label="Batch B - Shifted"
)

plt.scatter(
    widths, energy_b,
    color="red",
    marker="s",
    s=65,
    zorder=5
)


plt.fill_between(
    smooth_x,
    smooth_y_a,
    smooth_y_b,
    color="yellow",
    alpha=0.15,
    label="Energy Difference"
)

plt.title(
    "QUANTUM DOT ENERGY SCALING: BATCH COMPARISON",
    fontsize=13,
    fontweight="bold",
    pad=16
)

plt.xlabel("Quantum Dot Width (nm)", fontsize=11)
plt.ylabel("Electron Energy (eV)", fontsize=11)

plt.xlim(1.5, 10)
plt.ylim(0, 4)

plt.grid(True, linestyle="--", alpha=0.4)
plt.legend(loc="upper right", frameon=True)

plt.tight_layout()
plt.savefig("quantum_dot_comparison.png", dpi=300, bbox_inches="tight")
plt.show()